"""ci/matrix.py: loads and validates the verification matrix (ci/matrix.toml).

    python3 ci/matrix.py make    the make fragment (build/matrix.mk): config lists and per-config -D flags
    python3 ci/matrix.py show    the matrix as a table
"""
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

MATRIX = Path(__file__).resolve().parent / "matrix.toml"
# The stream unit jobs. A config with stream = "refused" gets one stream-refuse job in their place.
STREAM_UNIT_KINDS = ("lint-dec-stream", "sim-dec-stream", "lint-enc-stream", "sim-enc-stream", "sim-stream-rt")
JOB_KINDS = ("pkg", "lint", "sim", "inverse", "stream-ref") + STREAM_UNIT_KINDS + ("refuse", "guard")
PARAMS = ("precision", "symbol_width", "escape_slots")
STREAM_VALUES = ("supported", "refused")
# Contract version 3's scale estimator keys, refused by name since version 4.
EST_KEYS_GONE = ("est_frac", "est_shift", "est_m0", "est_mfloor", "est_k", "est_delay")


@dataclass(frozen=True)
class Config:
    name: str
    precision: int
    symbol_width: int
    escape_slots: int
    why: str
    refused: bool
    asic_period_ns: float = 0.0  # 0: no ASIC PPA target for this config
    stream: str = "supported"    # "refused": gen_pkg --stream must refuse it
    symmetric: bool = False      # symmetric_alphabet: -(2^(S-1) - 1) .. 2^(S-1) - 1 (SPEC.md §1)
    asic_period_ns_asap7: float = 0.0  # the same on ASAP7 (make ... ASIC_PLATFORM=asap7); 0: no ASAP7 run

    def defines(self) -> str:
        return (f"-DPANS_PRECISION={self.precision} -DPANS_SYMBOL_WIDTH={self.symbol_width} "
                f"-DPANS_ESCAPE_SLOTS={self.escape_slots}" + (" -DPANS_SYMMETRIC_ALPHABET=1" if self.symmetric else ""))


@dataclass(frozen=True)
class Tier:
    name: str
    jobs: tuple
    why: str


@dataclass(frozen=True)
class Matrix:
    configs: tuple   # supported builds
    refused: tuple   # builds the generator must refuse
    tiers: dict


def _config(name: str, table: dict, refused: bool) -> Config:
    missing = [p for p in PARAMS + ("why",) if p not in table]
    if missing:
        raise ValueError(f"{name}: missing {', '.join(missing)}")
    gone = sorted(set(table) & set(EST_KEYS_GONE))
    if gone:
        raise ValueError(f"{name}: {', '.join(gone)}: the scale estimator left the build at contract version 4")
    extra = set(table) - set(PARAMS) - {"why", "asic_period_ns", "asic_period_ns_asap7", "stream", "symmetric_alphabet"}
    if extra:
        raise ValueError(f"{name}: unknown keys {', '.join(sorted(extra))}")
    if not name.replace("_", "").isalnum():
        raise ValueError(f"{name}: config names are letters, digits and underscores")
    stream = str(table.get("stream", "supported"))
    if stream not in STREAM_VALUES:
        raise ValueError(f"{name}: stream must be one of {', '.join(STREAM_VALUES)}")
    if refused and "stream" in table:
        raise ValueError(f"{name}: a refused build has no stream key (the generator refuses it outright)")
    symmetric = table.get("symmetric_alphabet", False)
    if not isinstance(symmetric, bool):
        raise ValueError(f"{name}: symmetric_alphabet must be true or false")
    return Config(name, *(int(table[p]) for p in PARAMS), str(table["why"]), refused,
                  float(table.get("asic_period_ns", 0.0)), stream, symmetric,
                  float(table.get("asic_period_ns_asap7", 0.0)))


def load(path: Path = MATRIX) -> Matrix:
    data = tomllib.loads(path.read_text())
    unknown = set(data) - {"config", "refused", "tier"}
    if unknown:
        raise ValueError(f"unknown sections: {', '.join(sorted(unknown))}")
    configs = tuple(_config(n, t, False) for n, t in data.get("config", {}).items())
    refused = tuple(_config(n, t, True) for n, t in data.get("refused", {}).items())
    names = [c.name for c in configs + refused]
    if len(set(names)) != len(names):
        raise ValueError("a config name is used twice")
    builds = [(c.precision, c.symbol_width, c.escape_slots, c.symmetric) for c in configs + refused]
    if len(set(builds)) != len(builds):
        raise ValueError("two configs define the same build")
    tiers = {}
    for name, table in data.get("tier", {}).items():
        jobs = tuple(table.get("jobs", ()))
        bad = [j for j in jobs if j not in JOB_KINDS]
        if bad:
            raise ValueError(f"tier {name}: unknown jobs {', '.join(bad)}")
        tiers[name] = Tier(name, jobs, str(table.get("why", "")))
    if not configs:
        raise ValueError("no configs")
    return Matrix(configs, refused, tiers)


def make_fragment(m: Matrix) -> str:
    lines = ["# GENERATED by ci/matrix.py from ci/matrix.toml. Do not edit.",
             f"CONFIGS := {' '.join(c.name for c in m.configs)}",
             f"REFUSED := {' '.join(c.name for c in m.refused)}",
             f"STREAM_CONFIGS := {' '.join(c.name for c in m.configs if c.stream == 'supported')}",
             f"STREAM_REFUSED := {' '.join(c.name for c in m.configs if c.stream == 'refused')}"]
    lines += [f"CFG_DEFS_{c.name} := {c.defines()}" for c in m.configs + m.refused]
    lines += [f"ASIC_PERIOD_{c.name} := {c.asic_period_ns:g}" for c in m.configs if c.asic_period_ns > 0]
    lines += [f"ASIC_PERIOD_asap7_{c.name} := {c.asic_period_ns_asap7:g}"
              for c in m.configs if c.asic_period_ns_asap7 > 0]
    return "\n".join(lines) + "\n"


def main(argv: list) -> int:
    try:
        m = load()
    except (ValueError, tomllib.TOMLDecodeError) as e:
        print(f"ci/matrix.toml: {e}", file=sys.stderr)
        return 1
    if argv[1:] == ["make"]:
        sys.stdout.write(make_fragment(m))
    elif argv[1:] == ["show"]:
        for c in m.configs + m.refused:
            kind = "refused" if c.refused else "config"
            stream = "  [stream units refused]" if c.stream == "refused" else ""
            sym = "  [symmetric alphabet]" if c.symmetric else ""
            print(f"{kind:8} {c.name:10} P={c.precision:<3} SW={c.symbol_width:<3} E={c.escape_slots:<2} "
                  f"{c.why}{stream}{sym}")
        for t in m.tiers.values():
            print(f"tier     {t.name:10} {' '.join(t.jobs)}  ({t.why})")
    else:
        print(__doc__, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
